// Bundle verified MIDI bytes into a static script; no network or npm dependency.
import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url), Midi = require('../js/piano-midi.js');
const catalog = JSON.parse(fs.readFileSync(new URL('../data/piano-library.json', import.meta.url), 'utf8'));
const ids = new Set();
for (const item of catalog) {
  if (ids.has(item.id)) throw new Error('Duplicate piano ID: ' + item.id);
  ids.add(item.id);
  const bytes = Buffer.from(item.midiBase64, 'base64');
  if (bytes.length !== item.bytes || createHash('sha256').update(bytes).digest('hex') !== item.sha256) throw new Error('MIDI integrity: ' + item.id);
  const parsed = Midi.parse(bytes);
  item.duration = parsed.duration; item.noteCount = parsed.notes.length;
  if (!item.credit || !item.license || !item.source || (!item.licenseUrl && !item.userProvided)) throw new Error('Missing attribution: ' + item.id);
}
const generated = `/* Generated by tools/build-piano-library.mjs from data/piano-library.json.
 * MIDI assets retain their individual licenses and attribution; see docs/PIANO_SOURCES.md.
 * Original MIDI bytes are embedded unchanged. No external request is needed during playback.
 */
(function (root) {
  'use strict';
  const data = ${JSON.stringify(catalog)};
  const entries = Object.freeze(data.map(({ midiBase64, ...meta }) => Object.freeze(meta)));
  const byId = new Map(data.map(entry => [entry.id, entry])), cache = new Map();
  function load(id) {
    if (cache.has(id)) return cache.get(id);
    const entry = byId.get(id);
    if (!entry) throw new Error('Không tìm thấy bản nhạc có sẵn.');
    const midi = root.PianoMidi || (typeof require === 'function' ? require('./piano-midi.js') : null);
    if (!midi) throw new Error('Chưa tải được bộ đọc MIDI. Hãy tải lại trang.');
    const raw = typeof root.atob === 'function' ? root.atob(entry.midiBase64) : Buffer.from(entry.midiBase64, 'base64').toString('binary');
    const bytes = Uint8Array.from(raw, c => c.charCodeAt(0));
    const parsed = midi.parse(bytes);
    const song = Object.freeze({ notes: parsed.melody, timeline: parsed.timeline, duration: parsed.duration });
    cache.set(id, song); return song;
  }
  const api = Object.freeze({ entries, load });
  root.PianoLibrary = api;
  if (typeof module === 'object' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
`;
fs.writeFileSync(new URL('../js/piano-library.js', import.meta.url), generated);
console.log(`Bundled ${catalog.length} MIDI pieces (${catalog.reduce((n, s) => n + s.bytes, 0)} original bytes).`);
